// Track importer (PLAN-v3 T5): GeoJSON LineString (bacinger/f1-circuits layout) -> lib/game/tracks/<id>.ts
//   npx vite-node scripts/tracks/import-geojson.ts -- --in scripts/tracks/data/it-1922.geojson --id monza \
//     --name "Autodromo Nazionale Monza" --country Italy [--length 5793] [--start 9.2811,45.6190] [--out lib/game/tracks/monza.ts]
// See scripts/tracks/README.md. The emitted module is a skeleton: pit lane, DRS zones, sectors, width and elevation are
// PLACEHOLDERS to be authored in T6 before the track is registered.

import { readFileSync, writeFileSync } from 'node:fs';
import { importCircuit } from '../../lib/game/track/import';
import { encodePoints } from '../../lib/game/track/pointsCodec';

const argv = process.argv.slice(2);
const arg = (name: string): string | undefined => {
  const i = argv.indexOf(`--${name}`);
  return i >= 0 ? argv[i + 1] : undefined;
};
const need = (name: string): string => {
  const v = arg(name);
  if (!v) {
    console.error(`missing --${name}`);
    process.exit(2);
  }
  return v;
};

const input = need('in');
const id = need('id');
const name = need('name');
const country = need('country');
const out = arg('out') ?? `lib/game/tracks/${id}.ts`;
const lengthM = arg('length') ? Number(arg('length')) : undefined;
const start = arg('start')?.split(',').map(Number) as [number, number] | undefined;

const UNITS_PER_M = 10; // lib/game/units.ts
const circuit = importCircuit(readFileSync(input, 'utf8'), { lengthM, startLonLat: start });
const world = circuit.pointsM.map((p): [number, number] => [p[0] * UNITS_PER_M, p[1] * UNITS_PER_M]);
const L = circuit.lengthM;
const r1 = (v: number) => Math.round(v * 10) / 10;

const text = `// GENERATED by scripts/tracks/import-geojson.ts from ${input} — do not edit the data line by hand; re-run the importer.
// Source: bacinger/f1-circuits (MIT, © Tomislav Bacinger), geometry derived from OpenStreetMap (© OpenStreetMap contributors, ODbL). See CREDITS.md.
// Processing: equirectangular projection (x east, y south), centripetal Catmull-Rom, resampled to ${circuit.n} points (${(L / circuit.n).toFixed(3)} m),
// Laplacian smoothing (max move 1.5 m), scaled to ${L} m. Index 0 = ${start ? `the sample nearest ${start.join(', ')} (lon, lat)` : 'the first coordinate of the source file'} — NOT verified as the real start/finish line (T6).
import { decodePoints } from '../track/pointsCodec';
import type { TrackModule } from '../track/registry';
import type { TrackMeta } from '../track/types';

const meta: TrackMeta = {
  id: '${id}',
  name: '${name.replace(/'/g, "\\'")}',
  country: '${country}',
  lengthM: ${L},
  direction: '${circuit.direction}',
  // PLACEHOLDERS (T6 authors the real values from public track maps; mark them "approximate" there):
  widthM: 15,
  sectorsM: [${r1(L / 3)}, ${r1((2 * L) / 3)}],
  drsZones: [],
  pit: { side: 1, entryM: ${r1(L - 350)}, exitM: ${r1(150)}, boxStartM: ${r1(L - 300)}, boxEndM: ${r1(L - 180)}, speedLimitKmh: 80 },
  gridSlotSpacingM: 8,
  scenery: {},
};

const DATA = '${encodePoints(world)}';

const module: TrackModule = { meta, controlPoints: decodePoints(DATA), samplesPerPoint: 1 };
export default module;
`;
writeFileSync(out, text);
console.log(
  `wrote ${out}: ${circuit.n} points, ${L} m, ${circuit.direction}, scale ${circuit.stats.scale.toFixed(5)}, ` +
    `max curvature jump ${circuit.stats.maxCurvatureJump.toFixed(4)} 1/m, self-intersections ${circuit.stats.selfIntersections}, ` +
    `min separation ${circuit.stats.minSeparationM.toFixed(1)} m, ${(text.length / 1024).toFixed(1)} kB`
);
